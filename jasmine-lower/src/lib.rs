#![feature(rustc_private)]

extern crate rustc_errors;
extern crate rustc_hir;
extern crate rustc_middle;

mod java_ast;

use std::path::{Path, PathBuf};

use kerfuffle::kerfuffle;
use rustc_hir::def::DefKind;
use rustc_middle::ty::TyCtxt;
use snafu::ResultExt;

#[kerfuffle]
#[derive(Debug)]
pub enum JasmineError {
    #[diag("Failed to prepare out dir")]
    Prepare { source: java_ast::PrepareError },
}

pub fn run(tcx: TyCtxt<'_>, out_dir: &Path) -> Result<(), JasmineError> {
    let ast = java_ast::prepare(PathBuf::from(out_dir)).context(PrepareSnafu)?;

    let mut methods = String::new();

    // output literally anything
    for &local_def_id in tcx.mir_keys(()) {
        let def_id = local_def_id.to_def_id();

        match tcx.def_kind(def_id) {
            DefKind::Fn | DefKind::AssocFn | DefKind::Closure => {}
            _ => continue,
        }

        let path = tcx.def_path_str(def_id);
        let body = tcx.optimized_mir(def_id);

        println!(
            "fn `{path}`: {} basic block(s), {} local(s)",
            body.basic_blocks.len(),
            body.local_decls.len(),
        );

        let java_name = sanitize(&path);
        methods.push_str(&format!(
            "    // TODO: lower `{path}`\n    public static void {java_name}() {{ /* {} blocks */ }}\n\n",
            body.basic_blocks.len(),
        ));
    }

    let java_src =
        format!("// AUTO-GENERATED by jasmine\npublic final class Main {{\n{methods}}}\n");

    let out_path = out_dir.join("Main.java");
    // java_ast::write(&out_path, java_src).expect("write output");
    println!("wrote {}", out_path.display());

    Ok(())
}

fn sanitize(path: &str) -> String {
    path.chars()
        .map(|c| if c.is_alphanumeric() { c } else { '_' })
        .collect()
}
